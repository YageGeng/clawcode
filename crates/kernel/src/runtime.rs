/// Errors surfaced by kernel construction, persistence, extensions, and Turns.
#[derive(Debug, thiserror::Error)]
pub enum KernelError {
    /// Model construction or streaming failed.
    #[error(transparent)]
    Model(#[from] ModelError),
    /// Tool registry construction failed.
    #[error("tool subsystem failed: {0}")]
    Tool(#[from] tools::ToolError),
    /// Session persistence failed.
    #[error("store subsystem failed: {0}")]
    Store(#[from] store::StoreError),
    /// Extension construction or dispatch failed.
    #[error("extension subsystem failed: {0}")]
    Extension(#[from] extension::ExtensionError),
    /// Session-scoped MCP construction failed.
    #[error("MCP subsystem failed: {0}")]
    Mcp(#[from] mcp::McpError),
    /// Skill discovery or invocation failed.
    #[error("skill subsystem failed: {0}")]
    Skill(#[from] skill::SkillError),
    /// System prompt construction or project context discovery failed.
    #[error("system prompt failed: {0}")]
    Prompt(#[from] crate::PromptError),
    /// A live event consumer failed.
    #[error(transparent)]
    Sink(#[from] SinkError),
    /// A requested session has not been registered with this kernel.
    #[error("session not found: {0}")]
    SessionNotFound(SessionId),
    /// A session identifier was registered more than once.
    #[error("session already exists: {0}")]
    DuplicateSession(SessionId),
    /// A resume request supplied a different working directory for a live session.
    #[error(
        "session working directory mismatch for {session_id}: expected {expected:?}, received {received:?}"
    )]
    SessionCwdMismatch {
        session_id: SessionId,
        expected: PathBuf,
        received: PathBuf,
    },
    /// A protocol scalar generated by an injected component was invalid.
    #[error("invalid generated protocol value: {0}")]
    Protocol(String),
    /// An extension intentionally prevented an operation.
    #[error("extension blocked operation: {0}")]
    ExtensionBlocked(String),
    /// A run exceeded the configured safety bound on sequential Turns.
    #[error("run exceeded the maximum of {0} turns")]
    TurnLimit(usize),
    /// A shared runtime lock was poisoned by a failed task.
    #[error("kernel state lock was poisoned")]
    Poisoned,
    /// A requested extension command was not registered.
    #[error("extension command not found: {0}")]
    ExtensionCommandNotFound(String),
    /// Queue insertion requires a run that has already become active.
    #[error("session is not running: {0}")]
    SessionNotRunning(SessionId),
    /// A queue identifier did not match any pending message.
    #[error("pending message not found: {0}")]
    PendingMessageNotFound(QueueId),
}

/// Dependency-injected builder for one modular kernel lifecycle.
#[derive(typed_builder::TypedBuilder)]
pub struct KernelFactory {
    model_factory: Arc<dyn ModelFactory>,
    tool_factory: Arc<dyn ToolFactory>,
    store_factory: Arc<dyn StoreFactory>,
    extension_factory: Arc<dyn ExtensionFactory>,
    clock: Arc<dyn Clock>,
    id_generator: Arc<dyn IdGenerator>,
    /// Creates system messages and immutable project context snapshots.
    #[builder(default = Arc::new(PiSystemPromptFactory::default()))]
    system_prompt_factory: Arc<dyn SystemPromptFactory>,
    /// Optional session-scoped MCP tool factory.
    #[builder(default)]
    mcp_factory: Option<Arc<dyn mcp::McpFactory>>,
    /// Optional pi-compatible skill discovery factory.
    #[builder(default)]
    skill_factory: Option<Arc<dyn skill::SkillFactory>>,
    /// Bounds accidental endless tool loops while remaining configurable.
    #[builder(default = 64)]
    max_turns: usize,
    /// Controls how many recent user Turns remain verbatim after compaction.
    #[builder(default)]
    compaction_policy: CompactionPolicy,
    /// Controls transient Assistant retries across distinct Turns.
    #[builder(default)]
    retry_policy: RetryPolicy,
}

impl KernelFactory {
    /// Resolves every factory once and returns a ready session-owning kernel.
    pub fn build(self) -> Result<Kernel, KernelError> {
        let model = self.model_factory.create()?;
        let extensions = self.extension_factory.create()?;
        let mut tools = self.tool_factory.create()?;
        for tool in extensions.tools() {
            tools.register(tool)?;
        }
        let tools = Arc::new(tools);
        let skills = self
            .skill_factory
            .map(|factory| factory.create())
            .transpose()?;
        Ok(Kernel::builder()
            .model(model)
            .tools(tools)
            .store_factory(self.store_factory)
            .extensions(extensions)
            .clock(self.clock)
            .id_generator(self.id_generator)
            .system_prompt_factory(self.system_prompt_factory)
            .mcp_factory(self.mcp_factory)
            .skills(skills)
            .max_turns(self.max_turns)
            .compaction_policy(self.compaction_policy)
            .retry_policy(self.retry_policy)
            .sessions(RwLock::new(HashMap::new()))
            .build())
    }
}

/// Session-owning agent runtime that serializes runs per session.
#[derive(typed_builder::TypedBuilder)]
pub struct Kernel {
    model: Arc<dyn Model>,
    tools: Arc<ToolRegistry>,
    store_factory: Arc<dyn StoreFactory>,
    extensions: ExtensionPipeline,
    clock: Arc<dyn Clock>,
    id_generator: Arc<dyn IdGenerator>,
    system_prompt_factory: Arc<dyn SystemPromptFactory>,
    #[builder(default)]
    mcp_factory: Option<Arc<dyn mcp::McpFactory>>,
    #[builder(default)]
    skills: Option<skill::SkillCatalog>,
    max_turns: usize,
    compaction_policy: CompactionPolicy,
    retry_policy: RetryPolicy,
    sessions: RwLock<HashMap<SessionId, Arc<SessionRuntime>>>,
}

impl Kernel {
    /// Invokes one discovered skill explicitly and returns its complete source.
    pub fn invoke_skill(&self, name: &str) -> Result<String, KernelError> {
        self.skills
            .as_ref()
            .ok_or_else(|| skill::SkillError::NotFound(name.to_string()))?
            .invoke(name)
            .map_err(KernelError::from)
    }

    /// Lists effective skill metadata without reading or returning skill bodies.
    #[must_use]
    pub fn skills(&self) -> Vec<SkillInfo> {
        self.skills
            .as_ref()
            .map_or_else(Vec::new, |catalog| catalog.descriptors())
    }

    /// Returns the immutable MCP status captured while building this session.
    pub fn mcp_status(
        &self,
        session_id: &SessionId,
    ) -> Result<Vec<McpServerInfo>, KernelError> {
        Ok(self.session(session_id)?.mcp_servers.to_vec())
    }

    /// Returns registered non-UI extension commands for protocol discovery.
    pub fn extension_commands(&self) -> Vec<ExtensionCommandDefinition> {
        self.extensions.commands()
    }

    /// Dispatches one registered extension command and returns its typed directive as JSON.
    pub async fn invoke_extension_command(
        &self,
        session_id: &SessionId,
        name: String,
        arguments: serde_json::Value,
    ) -> Result<serde_json::Value, KernelError> {
        if !self
            .extensions
            .commands()
            .iter()
            .any(|command| command.name == name)
        {
            return Err(KernelError::ExtensionCommandNotFound(name));
        }
        let directive = self
            .dispatch(
                ExtensionEvent::Command { name, arguments },
                session_id,
                None,
            )
            .await?;
        serde_json::to_value(directive).map_err(KernelError::from)
    }

    /// Generates and validates one transcript message identifier.
    fn message_id(&self) -> Result<MessageId, KernelError> {
        MessageId::try_from(self.id_generator.next(IdKind::Message))
            .map_err(|error| KernelError::Protocol(error.to_string()))
    }

    /// Dispatches one extension hook and converts an intentional block to a kernel error.
    async fn dispatch(
        &self,
        event: ExtensionEvent,
        session_id: &SessionId,
        turn_id: Option<TurnId>,
    ) -> Result<ExtensionEffects, KernelError> {
        let effects = self
            .extensions
            .dispatch(
                &event,
                &ExtensionContext {
                    session_id: session_id.clone(),
                    turn_id,
                },
            )
            .await?;
        if let Some(reason) = effects.block_reason.clone() {
            return Err(KernelError::ExtensionBlocked(reason));
        }
        Ok(effects)
    }
}

impl From<serde_json::Error> for KernelError {
    /// Treats persistence JSON conversion as a store-boundary failure.
    fn from(error: serde_json::Error) -> Self {
        Self::Store(store::StoreError::Json(error))
    }
}

#[derive(typed_builder::TypedBuilder)]
struct SessionRuntime {
    store: Mutex<Box<dyn SessionStore>>,
    lane: LaneId,
    cwd: PathBuf,
    tools: Arc<ToolRegistry>,
    mcp_servers: Arc<[McpServerInfo]>,
    project_context: ProjectContext,
    history: Mutex<Vec<AgentMessage>>,
    queue: Mutex<PendingQueue>,
    run_gate: AsyncMutex<()>,
    active_run_id: Mutex<Option<RunId>>,
    cancellation: Mutex<CancellationToken>,
    event_sequence: AtomicU64,
}

/// Clears active-run correlation on every success and error exit from `Kernel::run`.
struct ActiveRunLease {
    session: Arc<SessionRuntime>,
    run_id: RunId,
}

impl ActiveRunLease {
    /// Marks one run active after the session gate has been acquired.
    fn acquire(
        session: Arc<SessionRuntime>,
        run_id: RunId,
    ) -> Result<Self, KernelError> {
        *session
            .active_run_id
            .lock()
            .map_err(|_poison_error| KernelError::Poisoned)? =
            Some(run_id.clone());
        Ok(Self { session, run_id })
    }
}

impl Drop for ActiveRunLease {
    /// Clears only the run identity installed by this lease.
    fn drop(&mut self) {
        if let Ok(mut active_run_id) = self.session.active_run_id.lock()
            && active_run_id.as_ref() == Some(&self.run_id)
        {
            *active_run_id = None;
        }
    }
}

