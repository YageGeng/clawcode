impl EventEmitter {
    /// Emits one event using a fresh current timestamp from the injected clock.
    async fn emit(
        &self,
        turn_id: TurnId,
        payload: AgentEventPayload,
    ) -> Result<(), KernelError> {
        self.emit_at(turn_id, self.clock.now(), payload).await
    }

    /// Emits one event at an already captured output timestamp.
    async fn emit_at(
        &self,
        turn_id: TurnId,
        timestamp_ms: TimestampMs,
        payload: AgentEventPayload,
    ) -> Result<(), KernelError> {
        let raw_sequence = self
            .session
            .event_sequence
            .fetch_add(1, Ordering::Relaxed)
            .checked_add(1)
            .ok_or_else(|| {
                KernelError::Protocol("event sequence overflow".to_string())
            })?;
        let sequence = Sequence::try_from(raw_sequence)
            .map_err(|error| KernelError::Protocol(error.to_string()))?;
        self.sink
            .emit(AgentEvent {
                metadata: EventMetadata {
                    turn_id,
                    timestamp_ms,
                    sequence,
                },
                payload,
            })
            .await?;
        Ok(())
    }
}
