struct EventEmitter {
    clock: Arc<dyn Clock>,
    sink: Arc<dyn EventSink>,
    session: Arc<Session>,
}

impl EventEmitter {
    /// Emits one event using a fresh current timestamp from the injected clock.
    async fn emit(
        &self,
        turn_id: TurnId,
        payload: AgentEventPayload,
    ) -> Result<(), KernelError> {
        self.emit_at(turn_id, self.clock.now(), payload).await
    }

    /// Emits one event at an already captured output timestamp.
    async fn emit_at(
        &self,
        turn_id: TurnId,
        timestamp_ms: TimestampMs,
        payload: AgentEventPayload,
    ) -> Result<(), KernelError> {
        let sequence = self.session.execution.next_sequence()?;
        self.sink
            .emit(AgentEvent {
                metadata: EventMetadata {
                    turn_id,
                    timestamp_ms,
                    sequence,
                },
                payload,
            })
            .await?;
        Ok(())
    }
}

impl Kernel {
    /// Builds the emitter for an observer event raised outside a Run's own emitter.
    ///
    /// The event joins the running Turn and its sink when there is one, so it
    /// stays ordered with that Turn's events; an idle Session gets a fresh Turn.
    fn observer_emitter(
        &self,
        session: Arc<Session>,
        session_id: &SessionId,
    ) -> Result<(TurnId, EventEmitter), KernelError> {
        let active = session.execution.active_run()?;
        let turn_id = match &active {
            Some(active) => active.turn_id.clone(),
            None => self.new_turn_id()?,
        };
        let sink = active.map_or_else(
            || self.session_sink(session_id),
            |active| active.sink,
        );
        let emitter = EventEmitter {
            clock: Arc::clone(&self.clock),
            sink,
            session,
        };
        Ok((turn_id, emitter))
    }
}
