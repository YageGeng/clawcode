use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use config::ExtensionsConfig;
use protocol::ExtensionId;

/// Build-time projection that deliberately ignores runtime-only application settings.
#[derive(serde::Deserialize)]
struct ExtensionBuildConfig {
    /// Ordered modules selected for static compilation.
    #[serde(default)]
    extensions: ExtensionsConfig,
}

/// Failures that stop extension catalogue generation before Rust compilation.
#[derive(Debug, thiserror::Error)]
pub enum BuildConfigError {
    /// The selected TOML file could not be read or generated output could not be written.
    #[error("failed to {operation} extension build file {path}: {source}")]
    Io {
        /// Filesystem operation being attempted.
        operation: &'static str,
        /// Path involved in the failed operation.
        path: PathBuf,
        /// Underlying filesystem error.
        source: std::io::Error,
    },
    /// The selected application TOML was malformed.
    #[error("failed to parse extension build configuration: {0}")]
    Toml(#[from] toml::de::Error),
    /// One configured identifier cannot map safely to a Rust module.
    #[error("invalid extension identifier for static compilation: {0}")]
    InvalidExtensionId(String),
    /// One extension appeared more than once in the build list.
    #[error("extension appears more than once in build configuration: {0}")]
    DuplicateExtension(String),
    /// No available source file matched one configured extension.
    #[error("extension source is not available: {0}")]
    MissingExtensionSource(String),
    /// Both supported source layouts existed for one configured extension.
    #[error("extension source is ambiguous: {0}")]
    AmbiguousExtensionSource(String),
    /// A resolved source escaped the allowed extension source directory.
    #[error("extension source escapes the available root: {0}")]
    ExtensionSourceEscapesRoot(String),
}

/// Parsed build request and its resolved local Rust extension modules.
pub struct BuildConfiguration {
    config_path: PathBuf,
    available_root: PathBuf,
    sources: Vec<ExtensionSource>,
}

impl BuildConfiguration {
    /// Reads one parameterized application TOML and resolves enabled source modules.
    pub fn from_path(
        config_path: impl AsRef<Path>,
        available_root: impl AsRef<Path>,
    ) -> Result<Self, BuildConfigError> {
        let config_path = config_path.as_ref().to_path_buf();
        let available_root = available_root.as_ref().to_path_buf();
        let source =
            std::fs::read_to_string(&config_path).map_err(|source| {
                BuildConfigError::Io {
                    operation: "read",
                    path: config_path.clone(),
                    source,
                }
            })?;
        let build_config: ExtensionBuildConfig = toml::from_str(&source)?;
        let mut seen = BTreeSet::new();
        let mut sources =
            Vec::with_capacity(build_config.extensions.enabled.len());
        for extension_id in &build_config.extensions.enabled {
            if !seen.insert(extension_id.clone()) {
                return Err(BuildConfigError::DuplicateExtension(
                    extension_id.to_string(),
                ));
            }
            sources
                .push(ExtensionSource::resolve(extension_id, &available_root)?);
        }
        Ok(Self {
            config_path,
            available_root,
            sources,
        })
    }

    /// Writes deterministic Rust module declarations and the compiled catalogue entry point.
    pub fn render(
        &self,
        output_path: impl AsRef<Path>,
    ) -> Result<(), BuildConfigError> {
        let output_path = output_path.as_ref();
        let mut generated = String::from(
            "// @generated by crates/extensions/build.rs; do not edit.\n\n",
        );
        for source in &self.sources {
            generated.push_str(&format!(
                "#[path = {:?}]\nmod {};\n",
                source.path.to_string_lossy(),
                source.module_name,
            ));
        }
        generated.push_str(
            "\n/// Returns the extension catalogue selected by the build configuration.\npub fn compiled_extensions() -> Result<extension::ExtensionCatalog, extension::ExtensionError> {\n",
        );
        if self.sources.is_empty() {
            generated
                .push_str("    extension::ExtensionCatalog::new(Vec::new())\n");
        } else {
            generated.push_str("    extension::ExtensionCatalog::new(vec![\n");
            for source in &self.sources {
                generated.push_str(&format!(
                    "        {}::definition(),\n",
                    source.module_name
                ));
            }
            generated.push_str("    ])\n");
        }
        generated.push_str("}\n");
        std::fs::write(output_path, generated).map_err(|source| {
            BuildConfigError::Io {
                operation: "write",
                path: output_path.to_path_buf(),
                source,
            }
        })
    }

    /// Returns the configuration path Cargo must monitor for rebuilds.
    pub fn config_path(&self) -> &Path {
        &self.config_path
    }

    /// Returns the available root for diagnostics and Cargo rebuild tracking.
    pub fn available_root(&self) -> &Path {
        &self.available_root
    }
}

/// One validated extension ID mapped to its Rust module and source file.
struct ExtensionSource {
    module_name: String,
    path: PathBuf,
}

impl ExtensionSource {
    /// Maps one safe kebab-case extension ID to exactly one local source layout.
    fn resolve(
        extension_id: &ExtensionId,
        available_root: &Path,
    ) -> Result<Self, BuildConfigError> {
        let value = extension_id.as_str();
        let valid = value.split('-').all(|part| {
            !part.is_empty()
                && part.bytes().enumerate().all(|(index, byte)| {
                    byte.is_ascii_lowercase()
                        || (index > 0 && byte.is_ascii_digit())
                })
        });
        if !valid {
            return Err(BuildConfigError::InvalidExtensionId(
                value.to_string(),
            ));
        }

        let module_name = value.replace('-', "_");
        if matches!(
            module_name.as_str(),
            "abstract"
                | "as"
                | "async"
                | "await"
                | "become"
                | "box"
                | "break"
                | "const"
                | "continue"
                | "crate"
                | "do"
                | "dyn"
                | "else"
                | "enum"
                | "extern"
                | "false"
                | "final"
                | "fn"
                | "for"
                | "gen"
                | "if"
                | "impl"
                | "in"
                | "let"
                | "loop"
                | "macro"
                | "match"
                | "mod"
                | "move"
                | "mut"
                | "override"
                | "priv"
                | "pub"
                | "ref"
                | "return"
                | "self"
                | "static"
                | "struct"
                | "super"
                | "trait"
                | "true"
                | "try"
                | "type"
                | "typeof"
                | "unsafe"
                | "unsized"
                | "use"
                | "virtual"
                | "where"
                | "while"
                | "yield"
        ) {
            return Err(BuildConfigError::InvalidExtensionId(
                value.to_string(),
            ));
        }
        let file_source = available_root.join(format!("{module_name}.rs"));
        let module_source = available_root.join(&module_name).join("mod.rs");
        let path = match (file_source.is_file(), module_source.is_file()) {
            (true, false) => file_source,
            (false, true) => module_source,
            (false, false) => {
                return Err(BuildConfigError::MissingExtensionSource(
                    value.to_string(),
                ));
            }
            (true, true) => {
                return Err(BuildConfigError::AmbiguousExtensionSource(
                    value.to_string(),
                ));
            }
        };
        let canonical_root =
            available_root.canonicalize().map_err(|source| {
                BuildConfigError::Io {
                    operation: "canonicalize",
                    path: available_root.to_path_buf(),
                    source,
                }
            })?;
        let canonical_path =
            path.canonicalize().map_err(|source| BuildConfigError::Io {
                operation: "canonicalize",
                path: path.clone(),
                source,
            })?;
        if !canonical_path.starts_with(&canonical_root) {
            return Err(BuildConfigError::ExtensionSourceEscapesRoot(
                value.to_string(),
            ));
        }
        Ok(Self {
            module_name,
            path: canonical_path,
        })
    }
}
